test_that("app clears derived results on uploads, parameter changes and failed reruns", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("bslib")
  app <- new.env(parent = globalenv())
  sys.source(system.file("app", "app.R", package = "bambamR"), envir = app)
  local_mocked_bindings(.run_de = function(...) stop("test engine unavailable"),
                        .package = "bambamR")
  shiny::testServer(app$server, {
    session$setInputs(de_method = "none", norm_method = "cpm", p_cutoff = 0.05,
                      fc_cutoff = 1, load_example = 1)
    session$setInputs(run_pipeline = 1)
    expect_identical(rv$status, "complete")
    expect_equal(unname(colSums(rv$norm_counts)), rep(1e6, ncol(rv$counts)))
    expect_null(rv$de_results)
    session$setInputs(de_method = "DESeq2")
    expect_null(rv$norm_counts)
    session$setInputs(run_pipeline = 2)
    expect_identical(rv$status, "failed")
    expect_null(rv$norm_counts)
    expect_match(rv$log_text, "test engine unavailable")
    session$setInputs(de_method = "none", run_pipeline = 3)
    expect_identical(rv$status, "complete")
    upload <- tempfile(fileext = ".csv")
    withr::defer(unlink(upload))
    writeLines(c("gene,single", "g1,10", "g2,20"), upload)
    session$setInputs(count_file = data.frame(name = "counts.csv", datapath = upload))
    expect_null(rv$norm_counts)
    expect_null(rv$de_results)
    expect_equal(dim(rv$counts), c(2L, 1L))
    session$setInputs(run_pipeline = 4)
    expect_identical(rv$status, "failed")
    expect_null(rv$norm_counts)
    expect_match(rv$log_text, "match all count sample names")
    writeLines(c("gene,single", "g1,-10"), upload)
    session$setInputs(count_file = data.frame(name = "invalid.csv", datapath = upload))
    expect_null(rv$counts)
    expect_match(rv$log_text, "non-negative")
  })
})
